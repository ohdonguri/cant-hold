// 이 표가 같은 판을 가리킨다.
const SEED = 12345;

function seedRandom() {
  const orig = Math.random;
  let s = SEED >>> 0;
  let n = 0;
  Math.random = () => { n++; s = (s * 1664525 + 1013904223) >>> 0; return s / 2 ** 32; };
  return { calls: () => n, restore: () => { Math.random = orig; } };
}

