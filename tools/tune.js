// 밸런스 상수 역산. 그리디 플레이어가 몇 웨이브에서 죽는지로 난이도를 잰다.
// 목표: 그리디(대충 하는 플레이)가 18~24 웨이브에서 죽을 것.
// 그보다 일찍 죽으면 잘해도 못 깨고, 늦게 죽으면 생각할 필요가 없는 게임이다.
const { load, greedy } = require('./sim.js');

const TRIALS = Number(process.env.TRIALS || 5);

const BAND = [18, 24];

// ── 어느 스테이지로 재는가 ────────────────────────────────────
// 이게 안 적혀 있어서 사고가 났다(#28). greedy 는 opts.stage 가 없으면 0(스테이지1)
// 을 집는데, 스테이지1 은 **원래 깨지라고 만든 판**이다. 그래서 실배포 행이 99
// (클리어)로 찍혔고 그걸 「밸런스가 망가졌다」로 읽어 GOLD_BASE 를 내릴 뻔했다.
// 실제로는 스테이지1 이 34/35덱 클리어인 게 정상이고, 내리면 6/8 → 3/8 로 **첫
// 스테이지가 안 열리는** 쪽으로 망가진다. 난이도의 정의는 뒤 스테이지에 있다.
//
// 35덱 × 6회 실측(현재 CFG · 클리어는 99 · **덱마다 시드 12345 를 다시 박음** —
// 아래 run() 과 같은 관례다. 스윕 전체에 한 번만 박으면 다른 표가 나온다):
//   스테이지  총웨이브  전체평균  최고덱  클리어덱
//      1        20       96.4    99.0   35/35   ← 대충 해도 깨진다(의도)
//      2        25       60.1    99.0   23/35   ← 절반을 훌쩍 넘게 깬다
//      3        30       30.1    64.5    6/35
//      4        30       28.6    40.7    2/35
//
// [2026-08 #31] 위 표를 통째로 새로 떴다. index.html 은 한 줄도 안 고쳤고, 바뀐 것은
// `tools/sim.js` 의 `pickKind` 다 — 그리디가 덱의 **셋째 종류를 아예 안 짓고 있었다.**
// 3종을 다 짓게 되자 네 스테이지 전부 쉬워졌다(옛 값 83.9 / 34.9 / 25.5 / 27.8,
// 클리어덱 34 / 17 / 0 / 0). 그러니 이 표는 「밸런스가 바뀌었다」가 아니라
// **「옛 표가 2종 플레이를 재고 있었다」**로 읽어야 한다.
//
// 그 결과 근거 ① 의 「17/35 → 0/35 경계」는 「23/35 → 6/35」로 무뎌졌다. 근거 ②③
// (「3 이 가장 어렵다」·「4 는 3 보다 쉽다」)은 **판정 불가**가 됐다 — 위 표는 4 가
// 더 어렵다고 하는데(28.6 대 30.1) 시딩만 바꾸면 뒤집힌다:
//   덱마다 재박음(위 표)  S3 30.1  S4 28.6   → 4 가 어렵다
//   스윕 전체 1회 시딩     S3 28.8  S4 30.7   → 3 이 어렵다
//   무시드                 S3 28.4  S4 30.9   → 3 이 어렵다
// 차이가 1~2웨이브로 같은 덱 반복 노이즈와 같은 자리수라 셋 다 노이즈 안일 수 있다.
// **그래서 STAGE 는 2 로 둔다.** 뒤집혔다는 근거도, 안 뒤집혔다는 근거도 이 표로는
// 못 만든다. 기준판을 옮기려면 시행수를 올려 신뢰구간부터 붙여야 하고, 그건 난이도를
// 다시 조이는 것과 같은 판단이라 따로 떼면 #28 을 반복한다. 다음 티켓이 둘을 같이 본다.
//
// **스테이지3(index 2, 갈래길)을 기준으로 삼는다.** 근거 셋이다.
//   ① 「그리디가 클리어해버리면 너무 쉬운 것」이라는 이 도구의 정의가 처음으로
//      만족되는 판이다. 클리어덱이 17/35 에서 0/35 로 떨어지는 경계가 여기고,
//      경계에서 재야 상수를 조금 움직였을 때 지표가 움직인다. 스테이지4 는 경계에서
//      더 멀어 같은 변화에 덜 반응한다
//   ② 네 스테이지 중 가장 어렵다. 전체평균 25.5 로 최저이고, DESIGN 이 기준선이라고
//      적은 **최고덱**도 28.0 으로 최저다. 기준선은 가장 빡빡한 판이어야 한다
//   ③ 스테이지4 는 3 보다 **쉽다**(전체평균 27.8, 최고덱 29.3). 계단이 1→2→3 까지만
//      단조이고 4 에서 되돌아온다. 그 자체가 별도로 볼 문제이고, 기준선을 거기 두면
//      「기준이 이상한 건지 판이 이상한 건지」를 못 가른다
//
// 덱 차이를 재려면 반드시 여기서 재야 한다는 근거도 같은 표에 있다. 덱 간 편차 대
// 같은 덱 반복 노이즈가 스테이지1 은 0.21 대 0.14 로 아무것도 안 보이고(거의 전부
// 클리어라 상한에 눌린다), 스테이지3 은 1.64 대 1.51 이다.
const STAGE = 2;

// 그리드는 오래 [8, 14, 22, 32] 였다. 그동안 실배포 CFG.DMG_SCALE 은 6.5 로 내려가
// **그리드 최솟값보다 작아졌고**, GOLD_BASE 도 70 인데 그리드는 [22, 40] 이었다.
// 결과는 32행 전부 99(클리어) — 어느 행도 실제 게임이 아니어서 「목표 구간에 든
// 조합」이 실배포와 아무 상관 없는 값을 추천하고 있었다. 그리드가 재는 것은
// 실배포 주변이어야 의미가 있으므로 축마다 실배포값을 끼고 앞뒤로 벌린다.
//   DMG_SCALE   6.5  ← 4.5 / 6.5 / 9 / 13
//   STAR_RATIO  2.4  ← 2.4 / 2.7
//   GOLD_BASE   70   ← 55 / 70
//   GOLD_GROWTH 1.11 ← 1.11 / 1.16   (원래부터 실배포값을 끼고 있던 유일한 축)
// 행 수는 4×2×2×2 = 32 로 그대로 둔다. 축을 넓히면 조합이 곱으로 늘고, 어차피
// 클리어하는 행이 가장 오래 걸린다(99웨이브까지 굴린다).
const GRID = {
  DMG_SCALE:   [4.5, 6.5, 9, 13],
  STAR_RATIO:  [2.4, 2.7],
  GOLD_BASE:   [55, 70],
  GOLD_GROWTH: [1.11, 1.16],
};

function median(a) { const s = a.slice().sort((x, y) => x - y); return s[s.length >> 1]; }

// greedy 는 rollDeck·소환·적 배치까지 전역 Math.random 을 쓴다. 그대로 두면 같은
// 코드로 두 번 돌려도 「목표 구간에 든 조합」 목록이 달라졌다(실측: 없음 ↔ 3개).
// 그러면 이 도구의 출력은 근거로 쓸 수가 없다 — 밸런스를 정하는 회의에서 두 사람이
// 서로 다른 표를 들고 있게 된다. test.js 의 대등성 게이트가 같은 이유로 이미
// 시드를 밖에서 걸고 있으니(12345 · LCG) 같은 방식·같은 값을 쓴다.
//
// **run() 마다 다시 박는 것**이 핵심이다. 프로세스 시작에 한 번만 박으면 앞 행이
// 난수를 얼마나 먹었느냐에 뒤 행이 딸려서, 그리드에 행 하나를 더하면 그 아래
// 전부가 움직인다. 행마다 같은 난수열을 주면 조합끼리 같은 판으로 겨루게 되어
// (짝지은 비교) 조합 간 차이가 시드 운에 안 묻히고, 행을 더해도 남은 행이 안 흔들린다.
const SEED = 12345;
function seeded(fn) {
  const orig = Math.random;
  let s = SEED >>> 0;
  Math.random = () => { s = (s * 1664525 + 1013904223) >>> 0; return s / 2 ** 32; };
  try { return fn(); } finally { Math.random = orig; }
}

function run(overrides) {
  return seeded(() => {
    const waves = [], stars = [];
    for (let i = 0; i < TRIALS; i++) {
      const g = load(overrides);
      const r = greedy(g, { stage: STAGE });
      waves.push(r.result === 'clear' ? 99 : r.wave);
      stars.push(r.maxStar);
    }
    return { wave: median(waves), star: median(stars), waves };
  });
}

function inBand(w) { return w >= BAND[0] && w <= BAND[1]; }

// 그리드가 아무리 촘촘해도 답해 주지 않는 질문이 하나 있다: **지금 배포된 판은
// 밴드 안인가.** 그래서 아무것도 덮어쓰지 않은 한 행을 맨 위에 따로 찍는다.
// 그리드 축에 실배포값을 끼워 넣는 것만으로는 부족하다 — 그건 32행 중 한 행이라
// 눈으로 찾아야 하고, 축을 하나라도 손대면 그 행이 조합에서 사라진다.
function baseline() {
  const r = run({});
  console.log(`── 실배포 CFG (index.html 그대로, 아무것도 안 덮어씀) · 스테이지${STAGE + 1} ──`);
  console.log(
    '  사망웨이브(중앙값)', String(r.wave).padStart(3),
    '최고성급', r.star,
    '   ' + r.waves.join(','),
    '   ' + (inBand(r.wave) ? `목표 ${BAND[0]}~${BAND[1]} 안` : `목표 ${BAND[0]}~${BAND[1]} 밖 ← 손봐야 함`),
  );
  console.log();
  return r;
}

function grid() {
  const keys = Object.keys(GRID);
  const combos = keys.reduce((acc, k) =>
    acc.flatMap(o => GRID[k].map(v => ({ ...o, [k]: v }))), [{}]);

  const rows = [];
  for (const c of combos) {
    const r = run(c);
    rows.push({ ...c, ...r });
    console.log(
      keys.map(k => k + '=' + c[k]).join(' ').padEnd(62),
      '사망웨이브(중앙값)', String(r.wave).padStart(3),
      '최고성급', r.star,
      '   ' + r.waves.join(','),
    );
  }

  console.log(`\n── 목표(${BAND[0]}~${BAND[1]}) 구간에 든 조합 ──`);
  const hit = rows.filter(r => inBand(r.wave));
  if (!hit.length) console.log('없음. 그리드 범위를 넓혀야 한다.');
  for (const r of hit) console.log(' ', keys.map(k => k + '=' + r[k]).join(' '), '→ w' + r.wave);
}

if (process.argv[2] === 'one') {
  // 한 판만 볼 때도 시드를 박는다. 안 그러면 여기서 본 판을 다시 못 부른다.
  // 스테이지도 같이 박는다 — 그리드가 재는 판과 다른 판을 보면 볼 이유가 없다.
  console.log(JSON.stringify(seeded(() => greedy(load(), { stage: STAGE })), null, 1));
} else {
  baseline();
  grid();
}
